export function getTenantComments(tenantId: string): CustomerComment[] {
  return MOCK_TENANT_COMMENTS[tenantId] || MOCK_TENANT_COMMENTS['kemis-lounge'];
}

export function getSentimentCounts(comments: CustomerComment[]) {
  const positive = comments.filter((c) => c.sentiment === 'positive').length;
  const neutral = comments.filter((c) => c.sentiment === 'neutral').length;
  const negative = comments.filter((c) => c.sentiment === 'negative').length;
  const total = comments.length || 1;

  return {
    positive,
    neutral,
    negative,
    total: comments.length,
    positivePct: Math.round((positive / total) * 100),
    neutralPct: Math.round((neutral / total) * 100),
    negativePct: Math.round((negative / total) * 100),
  };
}
